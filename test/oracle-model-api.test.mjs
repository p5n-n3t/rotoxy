import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, chmod, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import express from 'express';
import { createServer } from 'node:http';
import { StateStore } from '../dist/store.js';
import { ModelCredentialStore } from '../dist/model-credentials.js';
import { createOracleModelApi } from '../dist/oracle-model-api.js';

test('private Oracle route authorizes scopes, pins destination, namespaces models and never retries', async t => {
  const dir = await mkdtemp(join(tmpdir(),'rotoxy-oracle-http-'));
  const old = process.env.ROTOXY_CONFIG_DIR;
  process.env.ROTOXY_CONFIG_DIR = dir;
  const store = new StateStore();
  await store.init({adminPassword:'synthetic-oracle-route-password'});
  const creds = new ModelCredentialStore(store);
  const read = await creds.issueToken({scopes:['model:read'],expiresInSeconds:60});
  const invoke = await creds.issueToken({scopes:['model:read','model:invoke'],expiresInSeconds:60});
  const tokenFile = join(dir,'oracle-token');
  await writeFile(tokenFile,'synthetic-private-oracle-key',{mode:0o600});
  const calls=[];
  let reject=false;
  const app=express();
  app.use(createOracleModelApi(store,{tokenFile,fetch:async(url,init)=>{
    calls.push({url,init});
    if(reject) throw Error('synthetic-private-oracle-key must not leak');
    return Response.json(init.method==='GET'?{object:'list',data:[{id:'qwen3.5:2b'}]}:{model:'qwen3.5:2b',choices:[{message:{content:'OK'}}]},{headers:{'x-oracle-host':'ora8'}});
  }}));
  const server=createServer(app);
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{server.closeAllConnections();await new Promise(resolve=>server.close(resolve));if(old===undefined)delete process.env.ROTOXY_CONFIG_DIR;else process.env.ROTOXY_CONFIG_DIR=old;await rm(dir,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}/providers/oracle/v1`;
  assert.equal((await fetch(base+'/models')).status,401);
  const headers={authorization:'Bearer '+invoke.token,'content-type':'application/json'};
  const body={model:'oracle/qwen3.5:2b',messages:[{role:'user',content:'Reply OK'}]};
  assert.equal((await fetch(base+'/chat/completions',{method:'POST',headers:{...headers,authorization:'Bearer '+read.token},body:JSON.stringify(body)})).status,401);
  assert.equal(calls.length,0);
  const catalog=await(await fetch(base+'/models',{headers})).json();
  assert.equal(catalog.data[0].id,'oracle/qwen3.5:2b');
  const completion=await fetch(base+'/chat/completions',{method:'POST',headers,body:JSON.stringify(body)});
  assert.equal(completion.headers.get('x-oracle-host'),'ora8');
  assert.equal(completion.headers.get('x-rotoxy-provider-path'),'oracle');
  const answer=await completion.json();
  assert.equal(answer.model,'oracle/qwen3.5:2b');
  assert.equal(calls[1].url,'http://100.114.191.111:8877/v1/chat/completions');
  assert.equal(JSON.parse(calls[1].init.body).model,'qwen3.5:2b');
  assert.equal(calls[1].init.headers.authorization,'Bearer synthetic-private-oracle-key');
  assert.equal((await fetch(base+'/chat/completions',{method:'POST',headers,body:JSON.stringify({...body,stream:true})})).status,400);
  assert.equal(calls.length,2);
  reject=true;
  const failed=await fetch(base+'/chat/completions',{method:'POST',headers,body:JSON.stringify(body)});
  assert.equal(failed.status,502);
  assert.doesNotMatch(await failed.text(),/synthetic-private/);
  assert.equal(calls.length,3,'ambiguous upstream failures are not replayed');
  await chmod(tokenFile,0o644);
  assert.equal((await fetch(base+'/models',{headers})).status,503);
  assert.equal(calls.length,3);
});
