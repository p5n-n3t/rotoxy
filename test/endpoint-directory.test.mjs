import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import express from 'express';
import {createServer} from 'node:http';
import {StateStore} from '../dist/store.js';
import {AdminSessions} from '../dist/admin-session.js';
import {endpointDirectory,createEndpointDirectoryRouter} from '../dist/endpoint-directory.js';
import {InferenceProviderStore} from '../dist/inference-providers.js';

test('endpoint directory is metadata-only, derives saved custom pools, and requires admin authentication',async t=>{
 const root=await mkdtemp(join(tmpdir(),'rotoxy-endpoints-'));
 const prior=process.env.TOKEN2OAUTH_CONFIG_DIR;
 process.env.TOKEN2OAUTH_CONFIG_DIR=root;
 t.after(async()=>{if(prior===undefined)delete process.env.TOKEN2OAUTH_CONFIG_DIR;else process.env.TOKEN2OAUTH_CONFIG_DIR=prior;await rm(root,{recursive:true,force:true});});
 const store=new StateStore();await store.init({adminPassword:'synthetic-directory-password'});
 const providers=new InferenceProviderStore(store);
 const custom=await providers.addCustomProvider('Nebius test','https://provider.example.com/v1');
 await providers.addAccount({provider:custom.id,label:'Synthetic',token:'synthetic-key-never-exposed',allowedModels:['exact/model-id']});
 const initial=await endpointDirectory(store);
 assert.equal(initial.find(e=>e.id===custom.id).status,'configured');
 assert.deepEqual(initial.find(e=>e.id===custom.id).models,['exact/model-id']);
 assert.ok(!JSON.stringify(initial).includes('synthetic-key-never-exposed'));
 assert.equal(initial.find(e=>e.id==='cloudflare').status,'not_configured');
 assert.ok(initial.every(e=>!e.url.includes('<24-char-id>')));
 const sessions=new AdminSessions();const token=sessions.create(60000,0);
 const app=express();app.use(createEndpointDirectoryRouter(store,sessions));
 const server=createServer(app);await new Promise(r=>server.listen(0,'127.0.0.1',r));t.after(()=>new Promise(r=>server.close(r)));
 const base=`http://127.0.0.1:${server.address().port}`;
 assert.equal((await fetch(base+'/admin/api/v1/endpoints')).status,401);
 const response=await fetch(base+'/admin/api/v1/endpoints',{headers:{cookie:`t2o_admin=${token}`}});
 assert.equal(response.status,200);const result=await response.json();assert.equal(result.evidence,'local_metadata');
 assert.ok(!JSON.stringify(result).includes('synthetic-directory-password'));
 const {execFileSync}=await import('node:child_process');
 const cli=JSON.parse(execFileSync(process.execPath,['dist/cli.js','endpoints','--json'],{encoding:'utf8',env:{...process.env,TOKEN2OAUTH_CONFIG_DIR:root},timeout:15000}));
 assert.deepEqual(cli.endpoints,result.endpoints);
 const html=await(await fetch(base+'/admin/endpoints',{headers:{cookie:`t2o_admin=${token}`}})).text();
 assert.match(html,/Connection endpoints/);assert.match(html,/Scoped model Bearer token/);
});
