import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,writeFile,chmod} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import express from 'express';
import {createServer} from 'node:http';
import {StateStore} from '../dist/store.js';
import {AdminSessions} from '../dist/admin-session.js';
import {endpointDirectory,createEndpointDirectoryRouter} from '../dist/endpoint-directory.js';
import {InferenceProviderStore} from '../dist/inference-providers.js';
import {CloudflareCredentialStore} from '../dist/cloudflare-ai.js';

test('endpoint directory is metadata-only, derives saved custom pools, and requires admin authentication',async t=>{
 const root=await mkdtemp(join(tmpdir(),'rotoxy-endpoints-'));
 const prior=process.env.TOKEN2OAUTH_CONFIG_DIR, priorOracle=process.env.ROTOXY_ORACLE_API_TOKEN_FILE;
 process.env.TOKEN2OAUTH_CONFIG_DIR=root;
 delete process.env.ROTOXY_ORACLE_API_TOKEN_FILE;
 t.after(async()=>{if(prior===undefined)delete process.env.TOKEN2OAUTH_CONFIG_DIR;else process.env.TOKEN2OAUTH_CONFIG_DIR=prior;if(priorOracle===undefined)delete process.env.ROTOXY_ORACLE_API_TOKEN_FILE;else process.env.ROTOXY_ORACLE_API_TOKEN_FILE=priorOracle;await rm(root,{recursive:true,force:true});});
 const store=new StateStore();await store.init({adminPassword:'synthetic-directory-password'});
 const providers=new InferenceProviderStore(store);
 const custom=await providers.addCustomProvider('Nebius test','https://provider.example.com/v1');
 await providers.addAccount({provider:custom.id,label:'Synthetic',token:'synthetic-key-never-exposed',allowedModels:['exact/model-id']});
 await providers.addAccount({provider:'openai',label:'OpenAI synthetic',token:'synthetic-openai-key',allowedModels:['gpt-4o-mini']});
 const cloudflare=new CloudflareCredentialStore(store);
 await cloudflare.addCredential({label:'CF synthetic',accountId:'0123456789abcdef0123456789abcdef',token:'synthetic-cf-token-never-exposed',allowedModels:['@cf/meta/llama-3.1-8b-instruct-fp8']});
 const oracleToken='synthetic-oracle-token-never-exposed';
 await writeFile(join(root,'oracle-api-token'),oracleToken,{mode:0o600});await chmod(join(root,'oracle-api-token'),0o600);
 const webToolsPath=join(root,'web-tools.json');
 await writeFile(webToolsPath,JSON.stringify({providers:{oracle:{enabled:true,features:{search:'supported',extract:'supported'}}},permissions:{clients:{},authenticatedClients:['web_search','web_extract']}}),{mode:0o600});
 await chmod(webToolsPath,0o600);
 const initial=await endpointDirectory(store,{webToolsConfigPath:webToolsPath});
 assert.equal(initial.find(e=>e.id===custom.id).status,'configured');
 assert.deepEqual(initial.find(e=>e.id===custom.id).models,[custom.id+'/exact/model-id']);
 assert.deepEqual(initial.find(e=>e.id==='openai').models,['openai/gpt-4o-mini']);
 assert.deepEqual(initial.find(e=>e.id==='cloudflare').models,['cloudflare/@cf/meta/llama-3.1-8b-instruct-fp8']);
 assert.equal(initial.find(e=>e.id==='oracle').status,'configured','private canonical token metadata is found without an environment override');
 assert.equal(initial.find(e=>e.id==='search').status,'configured','Oracle search readiness uses the validated enabled web-tools binding and the same private token check');
 assert.deepEqual(initial.find(e=>e.id==='search').operations,['search','fetch']);
 assert.ok(initial.find(e=>e.id==='cloudflare').url.endsWith('/providers/cloudflare/v1'));
 assert.ok(initial.find(e=>e.id==='oracle').url.endsWith('/providers/oracle/v1'));
 assert.ok(!initial.some(e=>e.url.includes('/mcp') && e.id!=='workspace' && e.id!=='search'),'the directory does not advertise unsupported pool MCP endpoints');
 assert.ok(!initial.some(e=>['codex','claude'].includes(e.id)),'CLI profiles are not presented as inference endpoints');
 assert.ok(!JSON.stringify(initial).includes('synthetic-key-never-exposed'));
 assert.ok(!JSON.stringify(initial).includes('synthetic-cf-token-never-exposed'));
 assert.ok(!JSON.stringify(initial).includes(oracleToken));
 assert.ok(initial.every(e=>!e.url.includes('<24-char-id>')));
 const sessions=new AdminSessions();const token=sessions.create(60000,0);
 const app=express();app.use(createEndpointDirectoryRouter(store,sessions));
 const server=createServer(app);await new Promise(r=>server.listen(0,'127.0.0.1',r));t.after(()=>new Promise(r=>server.close(r)));
 const base=`http://127.0.0.1:${server.address().port}`;
 assert.equal((await fetch(base+'/admin/api/v1/endpoints')).status,401);
 const response=await fetch(base+'/admin/api/v1/endpoints',{headers:{cookie:`t2o_admin=${token}`}});
 assert.equal(response.status,200);const result=await response.json();assert.equal(result.evidence,'local_metadata');
 assert.ok(!JSON.stringify(result).includes('synthetic-directory-password'));
 const {execFileSync}=await import('node:child_process');
 const cli=JSON.parse(execFileSync(process.execPath,['dist/cli.js','endpoints','--json'],{encoding:'utf8',env:{...process.env,TOKEN2OAUTH_CONFIG_DIR:root},timeout:15000}));
 assert.deepEqual(cli.endpoints,result.endpoints);
 const html=await(await fetch(base+'/admin/endpoints',{headers:{cookie:`t2o_admin=${token}`}})).text();
 assert.match(html,/Connection endpoints/);assert.match(html,/Scoped model Bearer token/);
});

test('Oracle endpoint metadata rejects insecure canonical files and never falls back around an explicit bad override',async t=>{
 const root=await mkdtemp(join(tmpdir(),'rotoxy-oracle-endpoint-readiness-'));
 const prior=process.env.TOKEN2OAUTH_CONFIG_DIR, priorOracle=process.env.ROTOXY_ORACLE_API_TOKEN_FILE;
 process.env.TOKEN2OAUTH_CONFIG_DIR=root;delete process.env.ROTOXY_ORACLE_API_TOKEN_FILE;
 t.after(async()=>{if(prior===undefined)delete process.env.TOKEN2OAUTH_CONFIG_DIR;else process.env.TOKEN2OAUTH_CONFIG_DIR=prior;if(priorOracle===undefined)delete process.env.ROTOXY_ORACLE_API_TOKEN_FILE;else process.env.ROTOXY_ORACLE_API_TOKEN_FILE=priorOracle;await rm(root,{recursive:true,force:true});});
 const store=new StateStore();await store.init({adminPassword:'synthetic-directory-password'});
 const canonical=join(root,'oracle-api-token');
 await writeFile(canonical,'synthetic-private-token',{mode:0o644});await chmod(canonical,0o644);
 let entries=await endpointDirectory(store);
 assert.equal(entries.find(e=>e.id==='oracle').status,'not_configured');
 process.env.ROTOXY_ORACLE_API_TOKEN_FILE='relative/untrusted-token-path';
 await chmod(canonical,0o600);
 entries=await endpointDirectory(store);
 assert.equal(entries.find(e=>e.id==='oracle').status,'not_configured','an explicit invalid path does not silently fall back to the canonical file');
 delete process.env.ROTOXY_ORACLE_API_TOKEN_FILE;
 entries=await endpointDirectory(store);
 assert.equal(entries.find(e=>e.id==='oracle').status,'configured');
 assert.ok(!JSON.stringify(entries).includes('synthetic-private-token'));
});
